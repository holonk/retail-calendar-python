"""Parity with the JS package.

The reference data in ``tests/data/golden`` is generated by ``scripts/golden/generate.mjs`` from the published
``retail-calendar`` npm package running in UTC. See that script for what each file covers.
"""

import csv
import datetime as dt
import functools
import gzip
import hashlib
import io
import json
from typing import Any

import pytest

from retail_calendar import (
    DateSegment,
    LastDayOfWeek,
    LastMonthOfYear,
    RetailCalendar,
    RetailCalendarOptions,
    WeekCalculation,
    WeekGrouping,
    date_to_segment,
    segment_to_date,
    week_of_gregorian_date,
)
from tests.helpers import DATA_DIR

GOLDEN_DIR = DATA_DIR / "golden"

# Must match CUSTOM_LEAP_YEARS in generate.mjs.
CUSTOM_LEAP_YEARS = [
    {"leap_year": 2005, "leap_year_end_date": dt.date(2006, 3, 11), "leap_year_frequency": 6},
    {"leap_year": 2018, "leap_year_end_date": dt.date(2019, 2, 2), "leap_year_frequency": 5},
    {"leap_year": 2023, "leap_year_end_date": dt.date(2024, 2, 3), "leap_year_frequency": 7},
]


def read_csv(name: str) -> list[dict[str, str]]:
    with gzip.open(GOLDEN_DIR / name, "rt", newline="") as file:
        return list(csv.DictReader(io.StringIO(file.read())))


@functools.cache
def configs() -> list[RetailCalendarOptions]:
    return [RetailCalendarOptions.from_dict(config) for config in json.loads((GOLDEN_DIR / "configs.json").read_text())]


def serialize(calendar: RetailCalendar, *, with_days: bool) -> dict[str, Any]:
    """The same shape as ``serialize`` in generate.mjs."""
    data: dict[str, Any] = {
        "numberOfWeeks": calendar.number_of_weeks,
        "weeks": [
            [
                week.week_of_year,
                week.week_of_month,
                week.week_of_quarter,
                week.month_of_year,
                week.quarter_of_year,
                week.start_date.isoformat(),
                week.end_date.isoformat(),
            ]
            for week in calendar.weeks
        ],
        "months": [
            [
                month.month_of_year,
                month.quarter_of_year,
                month.number_of_weeks,
                len(month.weeks),
                month.start_date.isoformat(),
                month.end_date.isoformat(),
            ]
            for month in calendar.months
        ],
    }
    if with_days:
        data["days"] = [
            [
                day.date.isoformat(),
                day.date.isoformat(),
                day.day_of_year,
                day.day_of_week,
                day.day_of_month,
                day.week_of_year,
                day.month_of_year,
                day.gregorian_month_of_year,
                day.gregorian_day_of_year,
                day.gregorian_day_of_month,
            ]
            for day in calendar.days
        ]
    return data


def digest(calendar: RetailCalendar) -> str:
    text = json.dumps(serialize(calendar, with_days=True), separators=(",", ":"))
    return hashlib.sha256(text.encode()).hexdigest()[:16]


def assert_no_mismatches(mismatches: list[str], total: int) -> None:
    assert not mismatches, f"{len(mismatches)} of {total} differ from the JS package, e.g.:\n" + "\n".join(
        mismatches[:10]
    )


@pytest.mark.parametrize("week_calculation", list(WeekCalculation), ids=lambda wc: wc.name)
def test_year_boundaries(week_calculation: WeekCalculation) -> None:
    rows = [row for row in read_csv("boundaries.csv.gz") if int(row["week_calculation"]) == week_calculation]
    assert rows
    mismatches = []
    for row in rows:
        custom = CUSTOM_LEAP_YEARS[int(row["custom_leap_year"])] if row["custom_leap_year"] else {}
        options = RetailCalendarOptions(
            week_grouping=WeekGrouping.GROUP_454,
            week_calculation=week_calculation,
            last_day_of_week=LastDayOfWeek(int(row["last_day_of_week"])),
            last_month_of_year=LastMonthOfYear(int(row["last_month_of_year"])),
            **custom,  # type: ignore[arg-type]
        )
        calendar = RetailCalendar(options, int(row["year"]))
        actual = (calendar.number_of_weeks, calendar.first_day.isoformat())
        expected = (int(row["number_of_weeks"]), row["first_day"])
        if actual != expected:
            mismatches.append(f"{row}: got {actual}")
    assert_no_mismatches(mismatches, len(rows))


def test_full_calendar_detail() -> None:
    with gzip.open(GOLDEN_DIR / "calendars.json.gz", "rt") as file:
        entries = json.load(file)
    assert len(entries) == len(configs())
    for entry in entries:
        options = configs()[entry["config"]]
        expected = {key: entry[key] for key in ("numberOfWeeks", "weeks", "months", "days") if key in entry}
        actual = serialize(RetailCalendar(options, entry["year"]), with_days="days" in entry)
        assert actual == expected, f"config {entry['config']} ({options}), year {entry['year']}"


@pytest.mark.parametrize("week_calculation", list(WeekCalculation), ids=lambda wc: wc.name)
def test_calendar_digests(week_calculation: WeekCalculation) -> None:
    rows = [
        row for row in read_csv("digests.csv.gz") if configs()[int(row["config"])].week_calculation == week_calculation
    ]
    assert rows
    mismatches = [
        f"config {row['config']} ({configs()[int(row['config'])]}), year {row['year']}"
        for row in rows
        if digest(RetailCalendar(configs()[int(row["config"])], int(row["year"]))) != row["digest"]
    ]
    assert_no_mismatches(mismatches, len(rows))


@pytest.mark.parametrize("week_calculation", list(WeekCalculation), ids=lambda wc: wc.name)
def test_week_of_gregorian_date_lookups(week_calculation: WeekCalculation) -> None:
    rows = [
        row for row in read_csv("lookups.csv.gz") if configs()[int(row["config"])].week_calculation == week_calculation
    ]
    assert rows
    mismatches = []
    for row in rows:
        options = configs()[int(row["config"])]
        date = dt.date.fromisoformat(row["date"])
        expected = DateSegment(year=int(row["year"]), week=int(row["week"]))
        found = week_of_gregorian_date(date, options)
        segment = date_to_segment(date, options)
        if (found.calendar.year, found.week.week_of_year) != (expected.year, expected.week) or segment != expected:
            mismatches.append(f"config {row['config']}, {date}: expected {expected}, got {segment}")
        elif not segment_to_date(segment, options) <= date < segment_to_date(segment, options) + dt.timedelta(days=7):
            mismatches.append(f"config {row['config']}, {date}: segment_to_date({segment}) does not contain it")
    assert_no_mismatches(mismatches, len(rows))
